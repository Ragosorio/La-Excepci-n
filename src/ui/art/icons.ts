function gearPath(): string {
  const teeth = 8;
  let d = '';
  for (let i = 0; i < teeth * 2; i++) {
    const a0 = (i / (teeth * 2)) * 360 - 90 - 360 / (teeth * 4) + 4;
    const a1 = ((i + 1) / (teeth * 2)) * 360 - 90 - 360 / (teeth * 4) - 4;
    const r = i % 2 === 0 ? 10 : 7.4;
    const p0 = polar(12, 12, r, a0);
    const p1 = polar(12, 12, r, a1);
    d += `${i === 0 ? 'M' : 'L'}${n2(p0.x)} ${n2(p0.y)}L${n2(p1.x)} ${n2(p1.y)}`;
  }
  return d + 'z';
}

