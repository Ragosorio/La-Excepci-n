function sunRays(r0: number, r1: number, count: number, w: number): string {
  let d = '';
  for (let i = 0; i < count; i++) {
    const a = (i / count) * 360 - 90;
    const p0 = polar(12, 12, r0, a);
    const p1 = polar(12, 12, r1, a);
    d += `M${n2(p0.x)} ${n2(p0.y)}L${n2(p1.x)} ${n2(p1.y)}`;
  }
  return st(d, w);
}

