/** Rough combat value for auto-resolve / arena odds (hp × dps weighting). */
export function unitPower(u: UnitDef, stars = 0): number {
  const vet = 1 + 0.15 * stars;
  const dps = u.damage / Math.max(0.3, u.attackCooldown);
  return Math.round(Math.sqrt(u.hp * (1 + u.armor) * dps * (u.attackRange > 4 ? 1.25 : 1)) * vet * 10) / 10;
}
